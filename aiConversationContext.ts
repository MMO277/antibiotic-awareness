export function matchPopularEgyptianDrug(rawText: string): PopularEgyptianDrugEntry | null {
  const x = norm(rawText);
  const lower = rawText.toLowerCase();
  for (const entry of POPULAR_EGYPTIAN_DRUGS) {
    for (const arName of entry.namesAr) {
      const nAr = norm(arName);
      const re = new RegExp(`(?:^|\\s)(?:ال)?${nAr}(?=$|\\s)`, 'i');
      if (nAr.length >= 3 && re.test(x)) return entry;
    }
    for (const enName of entry.namesEn) {
      const re = new RegExp(`\\b${enName.toLowerCase()}\\b`, 'i');
      if (enName.length >= 3 && re.test(lower)) return entry;
    }
  }
  return null;
}

