function matchConditionEnhanced(x: string): ConditionKind | null {
  const cleaned = x.replace(/بعد اذنك|بعد إذنك|باذن الله|بإذن الله|اذن الله/g, ' ');
  const base = matchCondition(cleaned);
  if (base) return base;
  if (/(?:^|\s)(?:ال)?(ودن|ودني|وداني|طبله الودن|وجع الودن)(?=$|\s)/.test(cleaned)) return 'ear';
  if (/(?:^|\s)(?:ال)?(سنان|سناني|ضرس|ضروسي|اللثه|وجع الضرس)(?=$|\s)/.test(cleaned)) return 'dental';
  if (/(?:^|\s)(?:ال)?(زوري|حلقي|اللوز|لوزتين|وجع الزور)(?=$|\s)/.test(cleaned)) return 'throat';
  if (/(?:^|\s)(?:ال)?(حرقان في البول|حرقان بول|المثانه|مسالك بوليه)(?=$|\s)/.test(cleaned)) return 'uti';
  if (/(?:^|\s)(?:ال)?(دمل|دمامل|خراج جلدي)(?=$|\s)/.test(cleaned)) return 'skin';
  if (/(?:^|\s)(?:ال)?(جيوب انفيه|الجيوب الانفيه)(?=$|\s)/.test(cleaned)) return 'sinus';
  if (/(?:^|\s)(?:ال)?(كحه ببلغم|بلغم اخضر|التهاب شعبي|التهاب رئوي)(?=$|\s)/.test(cleaned)) return 'chest';
  if (/(?:^|\s)(?:ال)?(جرثومه المعده|الجرثومه الحلزونيه)(?=$|\s)/.test(cleaned)) return 'stomach';
  return null;
}

